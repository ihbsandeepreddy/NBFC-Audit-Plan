export function searchRegulatoryLibrary(query: string): RegulatoryRef[] {
  const q = query.toLowerCase()
  return REGULATORY_LIBRARY.filter(r =>
    r.ref_number.toLowerCase().includes(q) ||
    r.title.toLowerCase().includes(q) ||
    r.short_excerpt.toLowerCase().includes(q) ||
    r.full_extract.toLowerCase().includes(q)
  )
}

export function getByCategory(category: RegulatoryCategory): RegulatoryRef[] {
  return REGULATORY_LIBRARY.filter(r => r.category === category)
}

export function getByArea(area: RegulatoryArea): RegulatoryRef[] {
  return REGULATORY_LIBRARY.filter(r => r.area.includes(area))
}
